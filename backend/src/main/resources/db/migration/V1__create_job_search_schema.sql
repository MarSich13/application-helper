CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    display_name VARCHAR(80) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE vacancies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(60) NOT NULL,
    external_id VARCHAR(200) NOT NULL,
    title VARCHAR(200) NOT NULL,
    company VARCHAR(200) NOT NULL,
    location VARCHAR(200) NOT NULL DEFAULT '',
    work_mode VARCHAR(20) NOT NULL,
    experience VARCHAR(100) NOT NULL DEFAULT '',
    salary VARCHAR(200) NOT NULL DEFAULT '',
    description TEXT NOT NULL,
    source_url VARCHAR(2000),
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_vacancy_source UNIQUE (source, external_id),
    CONSTRAINT ck_work_mode CHECK (work_mode IN ('REMOTE', 'HYBRID', 'ONSITE', 'UNSPECIFIED'))
);

CREATE TABLE vacancy_technologies (
    vacancy_id BIGINT NOT NULL REFERENCES vacancies(id) ON DELETE CASCADE,
    technology VARCHAR(40) NOT NULL,
    PRIMARY KEY (vacancy_id, technology)
);

CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    vacancy_id BIGINT NOT NULL REFERENCES vacancies(id),
    status VARCHAR(20) NOT NULL,
    notes TEXT NOT NULL DEFAULT '',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    status_changed_at TIMESTAMPTZ NOT NULL,
    applied_at TIMESTAMPTZ,
    CONSTRAINT uq_user_vacancy UNIQUE (user_id, vacancy_id),
    CONSTRAINT ck_application_status CHECK (status IN ('SAVED','APPLIED','INTERVIEW','OFFER','ACCEPTED','REJECTED','WITHDRAWN'))
);

CREATE TABLE status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES applications(id) ON DELETE CASCADE,
    from_status VARCHAR(20),
    to_status VARCHAR(20) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX ix_vacancies_created ON vacancies (created_at DESC, id DESC);
CREATE INDEX ix_applications_user_status ON applications (user_id, status);
CREATE INDEX ix_history_application ON status_history (application_id, changed_at, id);
CREATE INDEX ix_technologies_name ON vacancy_technologies (technology);
